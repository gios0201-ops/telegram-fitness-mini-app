export const catalogById = Object.fromEntries(
  Object.values(catalog)
    .flat()
    .map((e) => [e.id, e]),
);
export function defaultPlan(): Plan {
  return Object.fromEntries(
    Object.entries(catalog).map(([day, list]) => [
      day,
      list.map(
        ({ secondary, errors, aliases, media, ...exercise }) => exercise,
      ),
    ]),
  ) as Plan;
}
export function ranges(e: Exercise) {
  return `${e.setsMin && e.setsMin !== e.sets ? `${e.setsMin}–` : ""}${e.sets} × ${e.repsMin && e.repsMin !== e.reps ? `${e.repsMin}–` : ""}${e.reps}${e.repNote ? ` (${e.repNote})` : ""}`;
}

